# ==============================================================================
# CLEAN AND FORMAT THE TABLE
# ==============================================================================

cli::cli_h2("Formatting results table")

manuscript_stats <- stats_raw %>%
  # Focus on NEW results (current analysis)
  dplyr::select(Analysis, `Test Description`, `Model/Method`,
                test_statistic = `New Test Statistic`,
                df = `New df`,
                p_value = `New p-value`,
                effect_size = `New Effect Size`,
                Impact, Notes) %>%

  # Convert p_value to numeric (may be stored as character)
  dplyr::mutate(
    p_value = as.numeric(p_value),
    df = as.numeric(df)
  ) %>%

  # Add row numbers for easy reference
  dplyr::mutate(test_id = dplyr::row_number()) %>%

  # Clean up analysis categories
  dplyr::mutate(
    section = dplyr::case_when(
      stringr::str_detect(Analysis, "Coral Growth") ~ "Coral Growth",
      stringr::str_detect(Analysis, "Coral Physiology") ~ "Coral Physiology",
      stringr::str_detect(Analysis, "CAFI") ~ "CAFI-Coral Community",
      TRUE ~ Analysis
    )
  ) %>%

  # Add significance markers
  dplyr::mutate(
    significance = dplyr::case_when(
      is.na(p_value) ~ "—",
      p_value < 0.001 ~ "***",
      p_value < 0.01 ~ "**",
      p_value < 0.05 ~ "*",
      p_value < 0.1 ~ ".",
      TRUE ~ "NS"
    ),
    p_formatted = dplyr::case_when(
      is.na(p_value) ~ "—",
      p_value < 0.001 ~ "< 0.001",
      TRUE ~ sprintf("%.3f", p_value)
    )
  ) %>%

  # Add manuscript location hints
  dplyr::mutate(
    manuscript_location = dplyr::case_when(
      Impact == "PRIMARY" ~ "Results (Main findings)",
      Impact == "NEW" & p_value < 0.05 ~ "Results or Supplement",
      Impact == "INDIRECT" & p_value < 0.05 ~ "Results or Supplement",
      Impact == "UNCHANGED" ~ "Results",
      TRUE ~ "Methods or Supplement"
    )
  ) %>%

  # Reorder columns for clarity
  dplyr::select(test_id, section, Analysis, `Test Description`, `Model/Method`,
                test_statistic, df, p_value, p_formatted, significance,
                effect_size, Impact, manuscript_location, Notes)

