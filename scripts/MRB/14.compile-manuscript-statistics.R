# Refresh rows that are regenerated by the active Script 8 pipeline. The
# MANUSCRIPT_STATS_TABLE.csv source is a revision-era ledger, so these in-memory
# updates keep the submission-facing compiled table from preserving stale p-values.
update_stat_row <- function(stats, description, test_statistic = NULL, df = NULL,
                            p_value = NULL, effect_size = NULL, notes = NULL) {
  idx <- stats$`Test Description` == description
  if (!any(idx)) return(stats)
  if (!is.null(test_statistic)) stats$`New Test Statistic`[idx] <- test_statistic
  if (!is.null(df)) stats$`New df`[idx] <- df
  if (!is.null(p_value)) stats$`New p-value`[idx] <- p_value
  if (!is.null(effect_size)) stats$`New Effect Size`[idx] <- effect_size
  if (!is.null(notes)) stats$Notes[idx] <- notes
  stats
}

comm_summary_path <- here("output/MRB/tables/LMM_COMM_vs_COND_summary.csv")
if (file.exists(comm_summary_path)) {
  comm_summary <- readr::read_csv(comm_summary_path, show_col_types = FALSE)
  matrix_labels <- c("SQRT_CS", "HELLINGER", "SQRT")
  for (matrix_label in matrix_labels) {
    this_row <- comm_summary |>
      dplyr::filter(.data$Matrix == matrix_label) |>
      dplyr::slice(1)
    if (nrow(this_row) == 1L) {
      stats_raw <- update_stat_row(
        stats_raw,
        paste("Community vs Condition:", matrix_label),
        test_statistic = sprintf("t=%.3f", this_row$t_stat),
        df = sprintf("%.2f", this_row$DF),
        p_value = this_row$p_value,
        effect_size = sprintf(
          "beta=%.3f; 95%% CI [%.3f, %.3f]",
          this_row$Estimate, this_row$CI_lower, this_row$CI_upper
        ),
        notes = paste(
          "Current Script 8 fixed-effect summary from LMM_COMM_vs_COND_summary.csv;",
          "p-value from lmerTest denominator df."
        )
      )
    }
  }
}

stats_raw <- update_stat_row(
